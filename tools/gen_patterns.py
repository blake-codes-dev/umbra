#!/usr/bin/env python3
"""Generate src/native/patterns.h from patterns.json.

VAs in patterns.json are dump-relative, i.e. they are RVAs of a base-0 image, so the runtime
address is module_base + rva. Anything the core needs but nothing has measured yet is emitted
as 0, which makes the resolve stage fail loudly instead of calling a wild pointer.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WANTED = [
    "lua_pcall", "luau_load", "luau_compile", "lua_pushcclosure", "lua_createtable", "lua_setfield",
    "lua_rawseti", "lua_pushlstring", "lua_pushnumber", "lua_pushboolean", "lua_tolstring",
    "lua_tonumber", "lua_gettop", "luau_execute_dispatch", "luaG_runerror",
]

HEADER = """/* generated by tools/gen_patterns.py - do not edit by hand */
#ifndef LYPHEN_PATTERNS_H
#define LYPHEN_PATTERNS_H

#define LYPHEN_CLIENT_VERSION "{version}"

/* rva of each resolved function, 0 = not measured yet; sig is the scan fallback */
{entries}
/* image sanity: a hit must sit inside the code section the patterns were measured against */
#define LYPHEN_TEXT_SIZE 0x{text:x}u
#endif
"""


def main() -> int:
    data = json.loads((ROOT / "patterns.json").read_text())
    known = {}
    for pattern in data.get("patterns", []):
        va = pattern.get("func_va")
        if va:
            known[pattern["name"]] = int(va, 16)

    sigs = {}
    for pattern in data.get("patterns", []):
        if pattern.get("sig"):
            sigs[pattern["name"]] = pattern["sig"]

    entries = []
    missing = []
    for name in WANTED:
        rva = known.get(name, 0)
        if not rva:
            missing.append(name)
        entries.append(f"#define LYPHEN_RVA_{name.upper()} 0x{rva:x}u")
        sig = sigs.get(name)
        if sig:
            byte_list = ", ".join("0x" + b for b in sig.split())
            entries.append(f"static const unsigned char LYPHEN_SIG_{name.upper()}[] = {{ {byte_list} }};")
            entries.append(f"#define LYPHEN_SIGLEN_{name.upper()} {len(sig.split())}u")
        else:
            # the macro needs the symbol to exist; a 0 length skips the scan
            entries.append(f"static const unsigned char LYPHEN_SIG_{name.upper()}[] = {{ 0xCC }};")
            entries.append(f"#define LYPHEN_SIGLEN_{name.upper()} 0u")
    text = data.get("text_size", 0)

    target = ROOT / "src/native/patterns.h"
    body = HEADER.format(version=data.get("client_version", data.get("version", "unknown")),
                         entries="\n".join(entries), text=text)
    if target.exists() and target.read_text() == body:
        print("patterns.h unchanged")
    else:
        target.write_text(body)
        print(f"wrote {target.relative_to(ROOT)}")
    if missing:
        print("not measured yet: " + ", ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
