#!/usr/bin/env python3
"""Inline src/luau/library/*.luau into the menu between the LIBRARY markers.

The library files are plain statements, so the menu can run them without
loadstring (a ScreenGui in a LocalScript has none). The same text is also
offered to the editor, so an executor user can edit before running.

  python tools/build_menu.py          # rewrite the generated block
  python tools/build_menu.py --check  # fail if the block is stale
"""
from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MENU = ROOT / "src" / "luau" / "menu.luau"
LIB = ROOT / "src" / "luau" / "library"
BEGIN = "-- [[LIBRARY-BEGIN]] generated by tools/build_menu.py, do not hand-edit\n"
END = "-- [[LIBRARY-END]]\n"

# curated order: the things people actually reach for, first
ORDER = ["speed", "jump", "infjump", "noclip", "heal", "reset", "antiafk",
         "tpcursor", "copypos", "fullbright", "freecam", "spin", "fpsunlock", "rejoin"]


def entry(path: pathlib.Path) -> str:
    lines = path.read_text(encoding="utf-8").splitlines()
    name = desc = ""
    body = []
    for line in lines:
        if line.startswith("--!nocheck"):
            continue
        if line.startswith("-- name:") and not name:
            name = line.split(":", 1)[1].strip()
        elif line.startswith("-- desc:") and not desc:
            desc = line.split(":", 1)[1].strip()
        elif name and desc and line.startswith("--") and not body:
            continue
        else:
            body.append(line)
    while body and not body[0].strip():
        body.pop(0)
    source = "\n".join(body).rstrip()
    indented = "\n".join("        " + line if line.strip() else "" for line in source.splitlines())
    return (
        f'    {{ name = "{name}", desc = "{desc}",\n'
        f'      source = [==[\n{source}\n]==],\n'
        f"      code = function()\n{indented}\n      end }},\n"
    )


def block() -> str:
    files = {p.stem: p for p in LIB.glob("*.luau")}
    missing = [n for n in ORDER if n not in files]
    extra = [n for n in files if n not in ORDER]
    if missing or extra:
        print(f"library order out of sync: missing={missing} extra={extra}", file=sys.stderr)
        raise SystemExit(1)
    return BEGIN + "local LIBRARY = {\n" + "".join(entry(files[n]) for n in ORDER) + "}\n" + END


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = MENU.read_text(encoding="utf-8")
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    fresh = block()
    if args.check:
        if text[start:end] != fresh:
            print("menu.luau is stale, run tools/build_menu.py", file=sys.stderr)
            return 1
        print("library up to date")
        return 0
    MENU.write_text(text[:start] + fresh + text[end:], encoding="utf-8")
    print(f"inlined {len(ORDER)} library entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
